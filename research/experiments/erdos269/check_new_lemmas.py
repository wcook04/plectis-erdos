"""Independent exact finite checks for the added ordinary arguments.
Python 3.10+, standard library only. No floating-point logarithms.
This does not prove an infinite statement or execute Lean.
"""
from __future__ import annotations
from bisect import bisect_right
from fractions import Fraction as F
from pathlib import Path
import argparse, json, platform
from check_structures import literal_data, powers


def run(n: int) -> dict:
    P, m, z3, z5 = literal_data(n)
    p3, p5 = powers(3, 1 << n), powers(5, 1 << n)
    p9, p25 = powers(9, 1 << n), powers(25, 1 << n)
    terms = 0
    alphabet = set()
    for a in range(n):
        total, seen = 0, set()
        endpoint = 1 << (a + 1)
        for j, q3 in enumerate(p3):
            if q3 >= endpoint:
                break
            for k, q5 in enumerate(p5):
                odd = q3*q5
                if odd >= endpoint:
                    break
                # floor(log_2 odd), followed by the unique dyadic exponent.
                i = a - (odd.bit_length()-1)
                value = odd << i
                assert (1 << a) <= value < endpoint
                assert value not in seen
                seen.add(value)
                e3 = z3[a+1] - (bisect_right(p3, value)-1)
                e5 = z5[a+1] - (bisect_right(p5, value)-1)
                assert e3 in (0, 1) and e5 in (0, 1)
                weight = 3**e3 * 5**e5
                total += weight
                alphabet.add(weight)
                terms += 1
        assert total == m[a]
        lo = bisect_right(p9, 1 << a) * bisect_right(p25, 1 << a)
        assert lo <= total <= 15*(a+1)**2
        assert 8**a < 15*P[a] and P[a] <= 8**a
    windows = []
    for B, ell, h, expected in [
        (1,1,2,(4,60,47,13,9)),
        (7,1,3,(6,360,289,137,95)),
        (16,1,4,(9,10800,8735,640,352))]:
        W, forcing = 1, 0
        for a in range(ell,ell+h):
            b = P[a+1]//P[a]
            W *= b
            forcing = b*forcing + m[a]
        q = ell+h
        n_a = q + z3[q] + z5[q]
        K = B*(n_a*n_a+8*n_a+18)//9
        R = (-B*forcing-1) % W + 1
        actual = (n_a-1,W,forcing,R,K)
        assert actual == expected
        assert R > K
        windows.append(dict(B=B,start=ell,length=h,strict_jump_index=n_a-1,
                            W=W,F=forcing,R=R,K=K,in_coprime_domain=(B in (1,7))))
    # Exact sums of 1, t and t^2 weighted by (1/12)^t.
    moments = (F(12,11),F(12,121),F(156,1331))
    qchecks = []
    for n_a in (0,1,2,3,100):
        total = F(0)
        for c, denom in ((0,1),(1,2),(2,6)):
            v = n_a+c+3
            total += (9*moments[2]+6*v*moments[1]+v*v*moments[0])/(18*denom)
        target = F(1210*n_a*n_a+9130*n_a+18847,11979)
        assert total == target
        Q = F(n_a*n_a+8*n_a+18,9)
        assert 11979*(Q-target) == 121*n_a*n_a+1518*n_a+5111
        qchecks.append(dict(n=n_a,Qtilde=str(target)))
    # Cancellation diagnostic: each exact pair sums to zero.
    cancellation = []
    for r in (1,2,5,10,20):
        t = 2**r
        assert F(1,2**t) - F(2**r,2**(t+r)) == 0
        cancellation.append(dict(r=r,first_index=t,gap=r,pair_cancels=True))
    return dict(schema='erdos269_new_ordinary_checks_v1',python=platform.python_version(),
                n=n,triangle_shells_checked=n,triangle_terms_checked=terms,
                triangle_weight_alphabet=sorted(alphabet),lower_and_upper_bounds_exact=True,
                window_examples=windows,quadratic_geometric_checks=qchecks,
                generic_cancellation_pairs=cancellation,
                limits=['Finite tests supplement, but do not replace, the displayed ordinary proofs.',
                        'No claim that the generic cancellation diagnostic is generated by the literal shell sequence.',
                        'No Lean, Isabelle, Comparator, NanoDa or large archived scan was executed.'])


def main() -> None:
    p=argparse.ArgumentParser()
    p.add_argument('--n',type=int,default=192)
    p.add_argument('--output',type=Path,default=Path('new_ordinary_checks.json'))
    a=p.parse_args()
    if a.n < 6 or a.n > 1000:
        p.error('--n must be between 6 and 1000')
    result=run(a.n)
    a.output.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(result,ensure_ascii=False,indent=2))

if __name__ == '__main__':
    main()
