"""Search polynomial coordinates from three explicitly selected Lean definitions.

The generator never receives centeredState, its proof, or its paper explanation.
This is a reconstruction control using classical polynomial invariant synthesis,
not evidence of autonomous mathematical discovery or of algorithmic novelty.
"""
import argparse
import ast
import hashlib
import itertools
import json
from pathlib import Path
import time

import sympy as sp

VARS = sp.symbols('a D C')


def arithmetic(node, symbols):
    if isinstance(node, ast.Expression):
        return arithmetic(node.body, symbols)
    if isinstance(node, ast.Name) and node.id in symbols:
        return symbols[node.id]
    if isinstance(node, ast.Constant) and type(node.value) is int:
        return sp.Integer(node.value)
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        return -arithmetic(node.operand, symbols)
    if isinstance(node, ast.BinOp):
        left, right = arithmetic(node.left, symbols), arithmetic(node.right, symbols)
        if isinstance(node.op, ast.Add): return left + right
        if isinstance(node.op, ast.Sub): return left - right
        if isinstance(node.op, ast.Mult): return left * right
        if isinstance(node.op, ast.Pow) and right.is_Integer and 0 <= right <= 8:
            return left ** right
    raise ValueError('unsupported Lean arithmetic syntax: ' + ast.dump(node))


def monomials(degree):
    return [sp.prod(x**n for x, n in zip(VARS, powers))
            for powers in itertools.product(range(degree + 1), repeat=len(VARS))
            if sum(powers) <= degree]


def solve(transition, degree=2):
    basis = monomials(degree)
    substitution = dict(zip(VARS, transition))
    rows = []
    for power in range(5):
        differences = [sp.Poly(sp.expand(m.subs(substitution, simultaneous=True)
                                        - VARS[0]**power*m), *VARS) for m in basis]
        terms = sorted(set().union(*(set(p.monoms()) for p in differences)))
        matrix = sp.Matrix([[p.coeff_monomial(t) for p in differences] for t in terms])
        for vector in matrix.nullspace():
            expr = sp.expand(sum(c*m for c, m in zip(vector, basis)))
            if not expr.free_symbols: continue
            assert sp.expand(expr.subs(substitution, simultaneous=True)
                             - VARS[0]**power*expr) == 0
            rows.append({'power': power, 'expr': expr,
                         'matrix_shape': list(matrix.shape), 'matrix_rank': matrix.rank()})
    return rows


def lean_expr(e):
    if e.is_Integer: return '(' + str(e) + ')'
    if e.is_Symbol: return str(e)
    if e.is_Add: return '(' + ' + '.join(map(lean_expr, e.args)) + ')'
    if e.is_Mul: return '(' + ' * '.join(map(lean_expr, e.args)) + ')'
    if e.is_Pow and e.exp.is_Integer and e.exp >= 0:
        return '(' + lean_expr(e.base) + ' ^ ' + str(e.exp) + ')'
    raise ValueError('unsupported certificate expression ' + str(e))


def generate(rows, definitions):
    lines = ['-- SPDX-FileCopyrightText: 2026 Will Cook',
             '-- SPDX-License-Identifier: Apache-2.0',
             '-- Generated by search.py; proof checking is a separate step.',
             'import ErdosProblems.Erdos243.ReciprocalTailRigidity',
             'open ErdosProblems.Erdos243',
             'set_option linter.unusedVariables false',
             'set_option linter.unusedSimpArgs false',
             'namespace ConstructionSynthesis']
    for definition in definitions:
        args = ' '.join(definition['arguments'])
        # The exported polynomial equals the source body as integers; `rfl` asked for
        # definitional equality of two spellings of one polynomial, which Int does not give.
        lines += [f'example ({args} : ℤ) : {definition["name"]} {args} = {lean_expr(definition["expr"])} := by',
                  f'  simp only [{definition["name"]}]', '  ring']
    for i, row in enumerate(rows):
        name = f'coordinate{i}'
        row['declaration'] = 'ConstructionSynthesis.' + name + '_transport'
        lines += [f'def {name} (a D C : ℤ) : ℤ := {lean_expr(row["expr"])}',
                  f'theorem {name}_transport (a D C : ℤ) :',
                  f'    {name} (sylvesterNext a) (nextDenState a D) (nextTailState a D C) =',
                  f'    a ^ {row["power"]} * {name} a D C := by',
                  f'  simp only [{name}, sylvesterNext, nextDenState, nextTailState]',
                  '  ring', f'#print axioms {name}_transport']
    # Shared multipliers provide invariant ratios, generated without a target coordinate.
    pairs = [(i, j) for i in range(len(rows)) for j in range(i + 1, len(rows))
             if rows[i]['power'] == rows[j]['power']]
    independent = []
    for i, j in pairs:
        ratio = sp.cancel(rows[i]['expr'] / rows[j]['expr'])
        trial = [r[2] for r in independent] + [ratio]
        jacobian = sp.Matrix([[sp.diff(r, x) for x in VARS] for r in trial])
        if jacobian.rank() <= len(independent): continue
        independent.append((i, j, ratio))
        k = rows[i]['power']
        lines += [f'theorem ratio{i}_{j}_transport (a D C : ℤ)',
                  f'    (ha : a ≠ 0) (hd : coordinate{j} a D C ≠ 0) :',
                  f'    (coordinate{i} (sylvesterNext a) (nextDenState a D) (nextTailState a D C) : ℚ) /',
                  f'      coordinate{j} (sylvesterNext a) (nextDenState a D) (nextTailState a D C) =',
                  f'    (coordinate{i} a D C : ℚ) / coordinate{j} a D C := by',
                  f'  rw [coordinate{i}_transport, coordinate{j}_transport]',
                  '  push_cast',
                  '  have haQ : (a : ℚ) ≠ 0 := by exact_mod_cast ha',
                  f'  have hdQ : (coordinate{j} a D C : ℚ) ≠ 0 := by exact_mod_cast hd',
                  '  field_simp', f'#print axioms ratio{i}_{j}_transport']
    lines += ['end ConstructionSynthesis', '']
    return '\n'.join(lines), [{'numerator': i, 'denominator': j,
                                 'formula': str(r)} for i, j, r in independent]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--input', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    start = time.monotonic()
    packet = json.loads(args.input.read_text())
    definitions = packet['definitions']
    for row in definitions:
        row['expr'] = arithmetic(ast.parse(row['body'].replace('^', '**'), mode='eval'),
                                 {str(x): x for x in VARS})
    coordinates = solve([row['expr'] for row in definitions])
    proof, ratios = generate(coordinates, definitions)
    # A prospective coefficient sweep reuses exactly the same search, without adapters.
    a, D, C = VARS
    sweep = []
    for b, c in itertools.product(range(-2, 3), range(-2, 3)):
        found = solve([a*a+b*a+c, a*D, a*C-D])
        mixed = [str(r['expr']) for r in found if C in r['expr'].free_symbols]
        sweep.append({'b': b, 'c': c, 'coordinates_involving_C': mixed})
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'Generated.lean').write_text(proof)
    result = {'schema': 'construction-synthesis-control/1',
              'source': packet['source'],
              'input_definitions': [{k:v for k,v in r.items() if k != 'expr'} for r in definitions],
              'excluded_from_generator': ['centeredState', 'sylvesterDefect', 'proofs', 'paper text'],
              'search_class': 'polynomials of total degree <= 2; cofactors a^k for 0 <= k <= 4',
              'coordinates': [{**r, 'expr': str(r['expr'])} for r in coordinates],
              'independent_ratios': ratios, 'quadratic_coefficient_sweep': sweep,
              'seconds': time.monotonic()-start,
              'generated_sha256': hashlib.sha256(proof.encode()).hexdigest(),
              'evidence': 'exact symbolic computation; Lean validation recorded separately',
              'limitations': ['selected dynamics and search grammar authored by a human/agent',
                 'reconstruction control; algorithmic and mathematical novelty not claimed',
                 'no polynomial found means only absence within the bounded search class',
                 'generator sees only selected definitions; its designer knew the existing coordinate']}
    (args.output / 'search.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps({'coordinates':[str(r['expr']) for r in coordinates],
                      'ratios':ratios, 'sweep_mixed_hits':[r for r in sweep if r['coordinates_involving_C']],
                      'seconds':result['seconds']}, indent=2))

if __name__ == '__main__': main()
